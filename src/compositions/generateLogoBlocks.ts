/**
 * One-time codegen: reads brand/logo/assembly-*.svg and emits a literal
 * TS data file (logoBlocks.ts) grouping their exact polygon coordinates into
 * 8 blocks, tagged with which assembly wave first introduces each block.
 * Run with `pnpm run generate:logo-blocks`; re-run only if the brand SVGs change.
 */
import fs from "node:fs";
import path from "node:path";

const dir = path.join(import.meta.dirname, "..", "..", "brand", "logo");

interface Poly {
  points: string;
  fill: string;
}

function parsePolygons(file: string): Poly[] {
  const svg = fs.readFileSync(path.join(dir, file), "utf-8");
  return [...svg.matchAll(/<polygon points="([^"]+)" fill="([^"]+)">/g)].map((m) => ({
    points: m[1]!,
    fill: m[2]!,
  }));
}

function groupIntoBlocks(polys: Poly[]): [Poly, Poly, Poly][] {
  const blocks: [Poly, Poly, Poly][] = [];
  for (let i = 0; i < polys.length; i += 3) {
    blocks.push([polys[i]!, polys[i + 1]!, polys[i + 2]!]);
  }
  return blocks;
}

const blockKey = (block: [Poly, Poly, Poly]) => block[0].points.split(" ")[0]!;

const base = groupIntoBlocks(parsePolygons("assembly-01-base.svg"));
const sides = groupIntoBlocks(parsePolygons("assembly-02-sides.svg"));
const locked = groupIntoBlocks(parsePolygons("assembly-03-locked.svg"));

const baseKeys = new Set(base.map(blockKey));
const sidesKeys = new Set(sides.map(blockKey));

const FILL_TO_TOKEN: Record<string, string> = {
  "#FFFFFF": "color.paper",
  "#D4FF3A": "color.chartreuse",
  "#121212": "color.graphite",
};

function waveOf(block: [Poly, Poly, Poly]): number {
  const key = blockKey(block);
  if (baseKeys.has(key)) return 0;
  if (sidesKeys.has(key)) return 1;
  return 2;
}

const lines: string[] = [];
lines.push("// GENERATED by src/compositions/generateLogoBlocks.ts — do not edit by hand.");
lines.push('import { color } from "../tokens/index";');
lines.push("");
lines.push('export interface LogoFace {');
lines.push("  points: string;");
lines.push("  fill: string;");
lines.push("}");
lines.push("");
lines.push("export interface LogoBlock {");
lines.push("  wave: number;");
lines.push("  top: LogoFace;");
lines.push("  front: LogoFace;");
lines.push("  side: LogoFace;");
lines.push("}");
lines.push("");
lines.push("export const LOGO_BLOCKS: LogoBlock[] = [");
for (const block of locked) {
  const wave = waveOf(block);
  const [top, front, side] = block;
  const faceLit = (p: Poly) => `{ points: "${p.points}", fill: ${FILL_TO_TOKEN[p.fill] ?? `"${p.fill}"`} }`;
  lines.push(`  { wave: ${wave}, top: ${faceLit(top)}, front: ${faceLit(front)}, side: ${faceLit(side)} },`);
}
lines.push("];");
lines.push("");

const outPath = path.join(import.meta.dirname, "logoBlocks.ts");
fs.writeFileSync(outPath, lines.join("\n") + "\n");
console.log("Wrote", outPath);
console.log("Wave sizes:", [0, 1, 2].map((w) => locked.filter((b) => waveOf(b) === w).length));
